const assert = require("node:assert/strict");
const fs = require("node:fs"), path = require("node:path");
const { root, siteFiles } = require("../scripts/site-files.js");
const { siteUrl, homeHead, robots, sitemap } = require("../scripts/site-seo.js");
const settings = { siteUrl: "https://example.com/base/" };
assert.equal(siteUrl(settings, {}), settings.siteUrl);
assert.equal(siteUrl(settings, { VERCEL_PROJECT_PRODUCTION_URL: "real.vercel.app" }), "https://real.vercel.app/");
assert.equal(siteUrl(settings, { REAL_SITE_URL: "https://real.example", VERCEL_PROJECT_PRODUCTION_URL: "other.vercel.app" }), "https://real.example/");
for (const value of ["http://example.com", "https://user:pass@example.com", "https://example.com/?token=x", "https://example.com/#room"]) assert.throws(() => siteUrl({ siteUrl: value }, {}));
const head = homeHead("https://real.example/", "google_verification_code");
assert.match(head, /rel="canonical" href="https:\/\/real.example\/"/);
assert.match(head, /google-site-verification/);
assert.match(head, /"@type":"WebSite"/);
assert.match(homeHead(settings.siteUrl), /"@type":"WebPage"/);
assert.throws(() => homeHead(settings.siteUrl, '<bad-token>'));
assert.match(robots("https://real.example/"), /Sitemap: https:\/\/real.example\/sitemap.xml/);
assert.doesNotMatch(robots(settings.siteUrl), /Disallow: \/mesa/);
assert.equal(robots(settings.siteUrl, true), "User-agent: *\nDisallow: /\n");
assert.equal((sitemap(settings.siteUrl).match(/<loc>/g) || []).length, 1);
assert.doesNotMatch(sitemap(settings.siteUrl, true), /<loc>/);
for (const page of ["mesa.html", "mesa-jogador.html"]) assert.match(fs.readFileSync(path.join(root, page), "utf8"), /name="robots" content="noindex, nofollow"/);
assert.match(fs.readFileSync(path.join(root, "apoie.html"), "utf8"), /name="robots" content="noindex, follow"/);
assert.ok(siteFiles().includes("assets/images/favicon.svg"));
assert.ok(siteFiles().every(file => !/^(archive|supabase|tests|scripts|outputs)\//.test(file)));
const config = JSON.parse(fs.readFileSync(path.join(root, "vercel.json"), "utf8"));
assert.equal(config.outputDirectory, "outputs/site");
assert.equal(config.buildCommand, "npm run build");
assert.ok(config.headers.find(item => item.source === "/mesa-jogador.html").headers.some(item => item.value === "noindex, nofollow"));
console.log("Publicação: endereço canônico, nome do site, sitemap só da página inicial, prévias e mesas fora da busca: OK");
